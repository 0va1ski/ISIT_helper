//Вариант 11: Найти площадь ромба по стороне и острому углу.
//Математическое решение: S = a^2 * sin(c)
//Ньюанс! sin острых углов cmath может находить как отрицательные значения.
//В таком случае переводим градусы в радианы (угол*Пи/180)

#include <iostream>
#include <cmath>
using namespace std;

int main() {
    double a, c, S;
    const double PI = acos(-1.0); //точное значение числа Пи
    cout << "\nВведите длину стороны ромба: ";
    cin >> a;
    cout << "Введите значение острого угла ромба: ";
    cin >> c;

    S = pow(a, 2) * sin(c*PI/180.0);
    cout << "Площадь ромба с заданными параметрами: " << S;
    return 0;
}