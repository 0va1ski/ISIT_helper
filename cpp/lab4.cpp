//Вариант 11: определить сколько делителей и какие имеет данное натуральное число

#include <iostream>
using namespace std;

int main() {
    int num, k=0;

    do {
        cout << "Введите натуральное число: ";
        cin >> num;
        if (num <= 0) {
            cout << "Ошибка! Число должно быть больше 0.\n";
        }
    } while (num <= 0);

    cout << "Делители числа: ";
    for (int i=1; i<=num; i++) {
        if (num%i == 0) {        
            cout << i << " ";
            k++;
        }
    }
    cout << "\nКоличество делителей: " << k << endl;

    return 0;
}